landscape_ui <- function(d) {
  library(shiny)
  if(is.null(d$landcover)) return(div(id='page-landscape',class='atlas-page',hidden=NA,
    h2('Explore landscape change'),p('The land-cover summaries have not been prepared in this checkout. See README.md for the local preparation step.')))
  e<-d$landcover$epochs;c<-d$landcover$classes
  div(id='page-landscape',class='atlas-page',hidden=NA,
    div(class='context-line','Victoria',span('1985-2019 historical epochs'),span('Land-cover classifications')),
    div(class='landscape-intro',h2('Put modelled priorities in landscape context'),
      p('Compare historical land cover in the same summary areas. Follow a class through seven epochs, or investigate net change between two periods.'),
      p(class='caption','Land cover ends in 2019. SMP4 is a July 2023 model snapshot. Neither source establishes management effects, habitat quality or ecological recovery.')),
    div(class='landscape-controls',
      selectizeInput('land_area','Focused summary area',choices=setNames(d$areas$microID,d$areas$Name),selected='unit668',options=list(maxOptions=100,onInitialize=I("function() { this.$control_input.attr('autocomplete', 'off'); }"))),
      selectInput('land_class','Land-cover class',choices=setNames(c$class_code,c$class_label),selected=12),
      selectInput('start_epoch','Start epoch',choices=setNames(head(e$epoch_id,-1),head(e$epoch_label,-1)),selected=e$epoch_id[1]),
      selectInput('end_epoch','End epoch',choices=setNames(e$epoch_id[-1],e$epoch_label[-1]),selected=tail(e$epoch_id,1))),
    div(class='workspace landscape-workspace',
      tags$aside(class='control-rail',`aria-label`='Landscape controls',
        selectInput('land_metric','Map measure',choices=c('Class share at end epoch'='share','Net class-share change'='change')),
        actionButton('land_zoom','Zoom to focused area',class='button-outline'),
        checkboxInput('land_context','Show place labels online',FALSE),
        actionButton('land_pin','Pin this area',class='button-primary'),
        div(class='pin-section',h3('Shared comparison'),uiOutput('land_pinned')),
        actionButton('land_clear','Clear comparison',class='button-outline'),
        downloadButton('download_landcover','Download selected areas',class='button-dark'),
        p(class='rail-note','Focus and pins are shared with Explore priorities. Each unit is analysed separately because boundaries overlap.')),
      div(class='map-region',leaflet::leafletOutput('landcover_map',height='520px'),
        div(class='map-caption',textOutput('land_map_caption'),span('Summary-area statistics; display boundaries simplified'))),
      tags$aside(class='detail-rail',`aria-label`='Landscape evidence',uiOutput('land_focus'))),
    tags$section(class='land-comparison-section',
      div(class='section-heading',h2('Compare the selected class'),p('Percentage points compare class shares. Hectares compare net mapped class area. These are not class-to-class transitions.')),
      uiOutput('land_comparison')),
    tags$section(class='land-change-section',
      div(class='section-heading',h2('Which classes changed in the focused area?'),
        radioButtons('change_unit',NULL,choices=c('Percentage points'='pp','Grid hectares'='ha'),inline=TRUE)),
      p(class='caption','Every class is shown. Ochre indicates a net decrease; green indicates a net increase. Colour does not indicate environmental benefit or harm.'),
      plotOutput('class_changes',height='590px')),
    tags$section(class='tableau-section',h2('Read the history'),
      p('The Tableau workbook shows the focused area\'s composition across all epochs and compares the selected class across focused and pinned areas.'),uiOutput('tableau')),
    tags$details(id='local-evidence',open=if(!tableau_config()$valid) NA else NULL,
      tags$summary('Local temporal evidence and exact values'),
      p(class='caption','Local evidence remains available without a published Tableau connection. Epochs are categories, not annual measurements.'),
      plotOutput('land_trends',height='330px'),
      div(class='evidence-scroll',uiOutput('land_values'))),
    p(class='method-note','Shares use classified area (codes 1-19) within each unit and epoch. Unclassified code 0 and missing coverage are excluded and reported separately. The earliest downloaded epoch is 1985-1990; the catalogue describes it as 1987-1990.'))
}
